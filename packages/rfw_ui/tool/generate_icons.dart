// Writes lib/src/decode/icons.g.dart: every icon `Icons` and `CupertinoIcons`
// declare, keyed by the name a remote file uses for it.
//
//   dart run tool/generate_icons.dart
//
// Run it after a Flutter upgrade. It reads the SDK's own icon files rather than
// a list kept here, so a new icon is one regeneration away and a removed one
// cannot linger as a name that compiles to nothing.
//
// The table holds the constants themselves (`Icons.home`), not codepoints. A
// map of const IconData is something the icon tree shaker can see, so an app
// that uses this package does not need --no-tree-shake-icons for these names.
import 'dart:io';

void main() {
  final Directory sdk = _flutterRoot();
  final List<String> material = _names(
    File('${sdk.path}/packages/flutter/lib/src/material/icons.dart'),
  );
  final List<String> cupertino = _names(
    File('${sdk.path}/packages/flutter/lib/src/cupertino/icons.dart'),
  );

  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_icons.dart from the Flutter SDK. Do not edit.')
    ..writeln('// ${material.length} Material and ${cupertino.length} Cupertino icons.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln()
    ..writeln("import 'package:flutter/cupertino.dart' show CupertinoIcons;")
    ..writeln("import 'package:flutter/material.dart' show IconData, Icons;")
    ..writeln()
    ..writeln('/// Every [Icons] constant, by its Dart name.')
    ..writeln('const Map<String, IconData> materialIcons = <String, IconData>{');
  for (final String name in material) {
    out.writeln("  '$name': Icons.$name,");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// Every [CupertinoIcons] constant, by its Dart name.')
    ..writeln('const Map<String, IconData> cupertinoIcons = <String, IconData>{');
  for (final String name in cupertino) {
    out.writeln("  '$name': CupertinoIcons.$name,");
  }
  out.writeln('};');

  File('lib/src/decode/icons.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote ${material.length} Material and ${cupertino.length} Cupertino icons');
}

/// The `static const IconData` names in one SDK file, skipping deprecated ones:
/// referring to them would put a deprecation warning in every app.
List<String> _names(File file) {
  final List<String> lines = file.readAsLinesSync();
  final RegExp declaration = RegExp(r'^\s*static const IconData (\w+)\s*=');
  final List<String> names = <String>[];
  for (int i = 0; i < lines.length; i += 1) {
    final RegExpMatch? match = declaration.firstMatch(lines[i]);
    if (match == null) {
      continue;
    }
    bool deprecated = false;
    for (int back = i - 1; back >= 0 && back >= i - 4; back -= 1) {
      final String line = lines[back].trim();
      if (line.startsWith('@Deprecated') || line.startsWith('@deprecated')) {
        deprecated = true;
        break;
      }
      // A previous declaration ends the annotations that could belong to this one.
      if (line.endsWith(';')) {
        break;
      }
    }
    if (!deprecated) {
      names.add(match.group(1)!);
    }
  }
  return names;
}

Directory _flutterRoot() {
  final ProcessResult which = Process.runSync('which', <String>['flutter']);
  final String bin = (which.stdout as String).trim();
  if (bin.isEmpty) {
    stderr.writeln('flutter is not on PATH');
    exit(1);
  }
  // <root>/bin/flutter, so the SDK is two levels up from the real binary.
  return File(File(bin).resolveSymbolicLinksSync()).parent.parent;
}
